/// <reference types="tree-sitter-cli/dsl" />
// @ts-check

const commaSeparated = rule => seq(rule, repeat(seq(',', rule)));
const keyword = word => token(prec(1, new RegExp(word, 'i')));

export default grammar({
  name: 'yt_sql',
  word: $ => $.ordinary_identifier,
  extras: $ => [/\s/, $.comment],
  conflicts: $ => [
    [$.predicate_only_query, $.parenthesised_boolean],
    [$.predicate, $.parenthesised_scalar],
    [$.relation_wildcard, $.scalar_atom],
  ],

  rules: {
    source_file: $ => $.query,
    query: $ => seq(optional($.with_clause), $.query_expression),
    query_expression: $ => seq(
      $.query_primary,
      repeat(seq($.union_operator, $.query_primary)),
      optional($.order_by_clause),
      optional($.limit_clause),
      optional($.offset_clause),
    ),
    query_primary: $ => choice($.select_query, $.predicate_only_query, seq('(', $.query_expression, ')')),
    predicate_only_query: $ => $.boolean_expression,
    union_operator: $ => prec.right(seq($.union_keyword, optional($.all_keyword))),

    with_clause: $ => seq($.with_keyword, commaSeparated($.cte)),
    cte: $ => seq($.identifier, $.as_keyword, '(', $.query_expression, ')'),

    select_query: $ => choice(
      seq(
        $.select_clause,
        optional($.from_clause),
        optional($.where_clause),
        optional($.group_by_clause),
        optional($.having_clause),
      ),
      seq($.from_clause, optional($.where_clause), optional($.group_by_clause), optional($.having_clause)),
      seq($.where_clause, optional($.group_by_clause), optional($.having_clause)),
      seq($.group_by_clause, optional($.having_clause)),
      $.having_clause,
    ),
    select_clause: $ => seq($.select_keyword, optional($.distinct_keyword), commaSeparated($.select_term)),
    select_term: $ => choice(
      $.projection_wildcard,
      $.relation_wildcard,
      seq($.scalar_expression, optional(seq($.as_keyword, field('alias', $.identifier)))),
    ),
    projection_wildcard: _ => '*',
    relation_wildcard: $ => seq($.identifier, '.', '*'),

    from_clause: $ => seq($.from_keyword, $.relation_reference, repeat($.join_clause)),
    relation_reference: $ => seq($.relation_operand, optional(seq($.as_keyword, field('alias', $.identifier)))),
    relation_operand: $ => choice(seq($.relation_source, optional($.facet_list)), $.derived_relation),
    relation_reference_single: $ => seq(
      choice(seq($.relation_source, optional($.single_facet)), $.derived_relation),
      optional(seq($.as_keyword, field('alias', $.identifier))),
    ),
    relation_source: $ => choice($.at_identifier, $.identifier, $.string),
    facet_list: $ => seq($.of_keyword, commaSeparated($.facet_reference)),
    single_facet: $ => seq($.of_keyword, $.facet_reference),
    facet_reference: $ => $.identifier,
    derived_relation: $ => seq('(', $.query_expression, ')'),
    join_clause: $ => seq($.join_kind, $.relation_reference_single, $.on_keyword, $.boolean_expression),
    join_kind: $ => choice(
      seq(optional($.inner_keyword), $.join_keyword),
      seq($.left_keyword, optional($.outer_keyword), $.join_keyword),
      seq($.semi_keyword, $.join_keyword),
      seq($.anti_keyword, $.join_keyword),
    ),

    where_clause: $ => seq($.where_keyword, $.boolean_expression),
    group_by_clause: $ => seq($.group_keyword, $.by_keyword, commaSeparated($.scalar_expression)),
    having_clause: $ => seq($.having_keyword, $.having_expression),
    order_by_clause: $ => seq($.order_keyword, $.by_keyword, commaSeparated($.order_term)),
    order_term: $ => seq($.scalar_expression, optional(choice($.asc_keyword, $.desc_keyword))),
    limit_clause: $ => seq($.limit_keyword, $.positive_integer_literal),
    offset_clause: $ => seq($.offset_keyword, $.integer_literal),

    boolean_expression: $ => choice(
      prec.left(1, seq($.boolean_expression, $.or_keyword, $.boolean_expression)),
      prec.left(2, seq($.boolean_expression, $.and_keyword, $.boolean_expression)),
      prec.right(3, seq($.not_keyword, $.boolean_expression)),
      $.boolean_primary,
    ),
    boolean_primary: $ => choice($.predicate, $.collection_predicate, $.parenthesised_boolean),
    parenthesised_boolean: $ => seq('(', $.boolean_expression, ')', optional($.truth_test)),
    collection_predicate: $ => seq(
      choice($.any_keyword, $.all_keyword),
      '(',
      $.scalar_expression,
      $.as_keyword,
      field('binding', $.identifier),
      $.where_keyword,
      $.boolean_expression,
      ')',
    ),
    predicate: $ => seq($.scalar_expression, optional($.predicate_suffix)),
    predicate_suffix: $ => choice(
      seq($.comparison_operator, $.comparison_value),
      seq(optional($.not_keyword), $.between_keyword, $.literal_value, $.and_keyword, $.literal_value),
      seq(optional($.not_keyword), $.in_keyword, '(', commaSeparated($.literal_value), ')'),
      seq(
        optional($.not_keyword),
        $.is_keyword,
        optional($.not_keyword),
        $.distinct_keyword,
        $.from_keyword,
        $.scalar_expression,
      ),
      seq(optional($.not_keyword), $.is_keyword, optional($.not_keyword), $.null_keyword),
      seq(optional($.not_keyword), $.is_keyword, optional($.not_keyword), $.truth_value),
      seq(optional($.not_keyword), $.text_operator, $.text_value),
      seq($.does_keyword, $.not_keyword, $.text_operator, $.text_value),
      seq($.natural_comparison, $.literal_value),
    ),
    comparison_operator: _ => choice('=', '!=', '<>', '<', '<=', '>', '>='),
    comparison_value: $ => seq($.scalar_expression, repeat($.literal_piece)),
    truth_test: $ => seq($.is_keyword, optional($.not_keyword), $.truth_value),
    truth_value: $ => choice($.true_keyword, $.false_keyword, $.unknown_keyword),
    text_operator: $ => choice(
      $.contain_keyword,
      $.contains_keyword,
      $.match_keyword,
      $.matches_keyword,
      $.like_keyword,
      $.ilike_keyword,
    ),
    natural_comparison: $ => choice(
      seq($.at_keyword, $.least_keyword),
      seq($.at_keyword, $.most_keyword),
      seq($.greater_keyword, $.than_keyword),
      seq($.more_keyword, $.than_keyword),
      seq($.less_keyword, $.than_keyword),
      seq($.equal_keyword, $.to_keyword),
      $.over_keyword,
      $.above_keyword,
      $.under_keyword,
      $.below_keyword,
      $.equals_keyword,
    ),

    having_expression: $ => choice(
      prec.left(1, seq($.having_expression, $.or_keyword, $.having_expression)),
      prec.left(2, seq($.having_expression, $.and_keyword, $.having_expression)),
      prec.right(3, seq(optional($.not_keyword), $.having_primary)),
    ),
    having_primary: $ => choice(
      seq($.having_predicate, optional($.truth_test)),
      seq('(', $.having_expression, ')', optional($.truth_test)),
    ),
    having_predicate: $ => seq(
      $.scalar_expression,
      choice(
        seq($.comparison_operator, $.scalar_expression),
        seq($.is_keyword, optional($.not_keyword), $.distinct_keyword, $.from_keyword, $.scalar_expression),
        seq($.is_keyword, optional($.not_keyword), $.null_keyword),
        seq($.is_keyword, optional($.not_keyword), $.truth_value),
      ),
    ),

    scalar_expression: $ => choice(
      prec.left(1, seq($.scalar_expression, choice('+', '-'), $.scalar_expression)),
      prec.left(2, seq($.scalar_expression, choice('*', '/', '%'), $.scalar_expression)),
      prec.right(3, seq(choice('+', '-'), $.scalar_expression)),
      $.postfix_expression,
    ),
    postfix_expression: $ => seq($.scalar_atom, repeat(choice($.index_suffix, $.member_suffix))),
    index_suffix: $ => seq('[', $.scalar_expression, ']'),
    member_suffix: $ => seq('.', $.identifier),
    scalar_atom: $ => choice(
      $.identifier,
      $.scalar_literal,
      $.temporal_literal,
      $.scalar_function,
      $.function_call,
      $.aggregate_function,
      $.collection_transform,
      $.case_expression,
      $.parenthesised_scalar,
    ),
    parenthesised_scalar: $ => seq('(', $.scalar_expression, ')'),
    case_expression: $ => seq(
      $.case_keyword,
      repeat1($.case_when),
      optional(seq($.else_keyword, $.scalar_expression)),
      $.end_keyword,
    ),
    case_when: $ => seq($.when_keyword, $.boolean_expression, $.then_keyword, $.scalar_expression),

    scalar_function: $ => choice(
      seq($.unary_scalar_function, '(', $.scalar_expression, ')'),
      seq($.multi_scalar_function, '(', $.scalar_expression, ',', commaSeparated($.scalar_expression), ')'),
      seq($.char_keyword, '(', commaSeparated($.scalar_expression), ')'),
      seq($.nullif_keyword, '(', $.scalar_expression, ',', $.scalar_expression, ')'),
      seq($.random_keyword, '(', optional($.scalar_expression), ')'),
    ),
    unary_scalar_function: $ => choice(
      $.lower_keyword,
      $.upper_keyword,
      $.length_keyword,
      $.cardinality_keyword,
    ),
    multi_scalar_function: $ => choice(
      $.coalesce_keyword,
      $.concat_keyword,
      $.greatest_keyword,
      $.least_keyword,
    ),
    function_call: $ => seq(field('name', $.identifier), '(', optional(commaSeparated($.scalar_expression)), ')'),
    aggregate_function: $ => choice(
      seq(
        $.count_keyword,
        '(',
        choice(
          '*',
          $.scalar_expression,
          seq($.scalar_expression, $.as_keyword, field('binding', $.identifier), $.where_keyword, $.boolean_expression),
        ),
        ')',
        optional($.aggregate_filter),
      ),
      seq($.aggregate_name, '(', $.scalar_expression, ')', optional($.aggregate_filter)),
    ),
    aggregate_name: $ => choice($.sum_keyword, $.min_keyword, $.max_keyword, $.avg_keyword),
    aggregate_filter: $ => seq($.filter_keyword, '(', $.where_keyword, $.boolean_expression, ')'),
    collection_transform: $ => choice(
      seq(
        $.filter_keyword,
        '(',
        $.scalar_expression,
        $.as_keyword,
        field('binding', $.identifier),
        $.where_keyword,
        $.boolean_expression,
        ')',
      ),
      seq(
        $.map_keyword,
        '(',
        $.scalar_expression,
        $.as_keyword,
        field('binding', $.identifier),
        $.select_keyword,
        $.scalar_expression,
        ')',
      ),
    ),

    scalar_literal: $ => choice(
      $.unit_literal,
      $.number,
      $.string,
      $.true_keyword,
      $.false_keyword,
      $.null_keyword,
    ),
    temporal_literal: $ => choice(
      $.infinity_literal,
      $.relative_temporal_literal,
      $.datetime,
      $.date,
      $.time,
    ),
    infinity_literal: _ => token(prec(4, /-?INFINITY\(\)/i)),
    relative_temporal_literal: $ => prec.right(seq(
      choice($.today_keyword, $.now_keyword),
      '(',
      ')',
      optional(seq(choice('+', '-'), $.temporal_quantity)),
    )),
    temporal_quantity: $ => choice(
      $.unit_literal,
      seq($.decimal_quantity, $.ordinary_identifier),
    ),
    literal_value: $ => $.literal_sequence,
    text_value: $ => $.literal_sequence,
    literal_sequence: $ => repeat1($.literal_piece),
    literal_piece: $ => choice($.identifier, $.scalar_literal, $.temporal_literal, '+', '-', '*', '/', '%'),

    select_keyword: _ => keyword('select'),
    from_keyword: _ => keyword('from'),
    where_keyword: _ => keyword('where'),
    with_keyword: _ => keyword('with'),
    group_keyword: _ => keyword('group'),
    having_keyword: _ => keyword('having'),
    order_keyword: _ => keyword('order'),
    by_keyword: _ => keyword('by'),
    limit_keyword: _ => keyword('limit'),
    offset_keyword: _ => keyword('offset'),
    as_keyword: _ => keyword('as'),
    asc_keyword: _ => keyword('asc'),
    desc_keyword: _ => keyword('desc'),
    distinct_keyword: _ => keyword('distinct'),
    or_keyword: _ => keyword('or'),
    and_keyword: _ => keyword('and'),
    not_keyword: _ => keyword('not'),
    any_keyword: _ => keyword('any'),
    all_keyword: _ => keyword('all'),
    union_keyword: _ => keyword('union'),
    of_keyword: _ => keyword('of'),
    on_keyword: _ => keyword('on'),
    join_keyword: _ => keyword('join'),
    inner_keyword: _ => keyword('inner'),
    left_keyword: _ => keyword('left'),
    outer_keyword: _ => keyword('outer'),
    semi_keyword: _ => keyword('semi'),
    anti_keyword: _ => keyword('anti'),
    is_keyword: _ => keyword('is'),
    null_keyword: _ => keyword('null'),
    true_keyword: _ => keyword('true'),
    false_keyword: _ => keyword('false'),
    unknown_keyword: _ => keyword('unknown'),
    between_keyword: _ => keyword('between'),
    in_keyword: _ => keyword('in'),
    does_keyword: _ => keyword('does'),
    contain_keyword: _ => keyword('contain'),
    contains_keyword: _ => keyword('contains'),
    match_keyword: _ => keyword('match'),
    matches_keyword: _ => keyword('matches'),
    like_keyword: _ => keyword('like'),
    ilike_keyword: _ => keyword('ilike'),
    at_keyword: _ => keyword('at'),
    least_keyword: _ => keyword('least'),
    most_keyword: _ => keyword('most'),
    greater_keyword: _ => keyword('greater'),
    more_keyword: _ => keyword('more'),
    less_keyword: _ => keyword('less'),
    than_keyword: _ => keyword('than'),
    equal_keyword: _ => keyword('equal'),
    to_keyword: _ => keyword('to'),
    over_keyword: _ => keyword('over'),
    above_keyword: _ => keyword('above'),
    under_keyword: _ => keyword('under'),
    below_keyword: _ => keyword('below'),
    equals_keyword: _ => keyword('equals'),
    case_keyword: _ => keyword('case'),
    when_keyword: _ => keyword('when'),
    then_keyword: _ => keyword('then'),
    else_keyword: _ => keyword('else'),
    end_keyword: _ => keyword('end'),
    coalesce_keyword: _ => keyword('coalesce'),
    concat_keyword: _ => keyword('concat'),
    greatest_keyword: _ => keyword('greatest'),
    lower_keyword: _ => keyword('lower'),
    upper_keyword: _ => keyword('upper'),
    length_keyword: _ => keyword('length'),
    cardinality_keyword: _ => keyword('cardinality'),
    char_keyword: _ => keyword('char'),
    nullif_keyword: _ => keyword('nullif'),
    random_keyword: _ => keyword('random'),
    count_keyword: _ => keyword('count'),
    sum_keyword: _ => keyword('sum'),
    min_keyword: _ => keyword('min'),
    max_keyword: _ => keyword('max'),
    avg_keyword: _ => keyword('avg'),
    filter_keyword: _ => keyword('filter'),
    map_keyword: _ => keyword('map'),
    today_keyword: _ => keyword('today'),
    now_keyword: _ => keyword('now'),

    identifier: $ => choice($.ordinary_identifier, $.quoted_identifier),
    ordinary_identifier: _ => /[\p{XID_Start}_][\p{XID_Continue}-]*(?:\.[\p{XID_Start}_][\p{XID_Continue}-]*)*/u,
    quoted_identifier: _ => /`(?:``|[^`])+`/,
    at_identifier: _ => /@[A-Za-z0-9_.-]+/,
    integer_literal: _ => /(?:0[xX][0-9a-fA-F](?:_?[0-9a-fA-F])*|0[oO][0-7](?:_?[0-7])*|0[bB][01](?:_?[01])*|\d(?:_?\d)*)/,
    positive_integer_literal: _ => /(?:0[xX](?:0_?)*[1-9a-fA-F](?:_?[0-9a-fA-F])*|0[oO](?:0_?)*[1-7](?:_?[0-7])*|0[bB](?:0_?)*1(?:_?[01])*|(?:0_?)*[1-9](?:_?\d)*)/,
    number: _ => /(?:0[xX][0-9A-Za-z_]+|0[oO][0-9A-Za-z_]+|0[bB][0-9A-Za-z_]+|\d[\d_]*(?:\.\d[\d_]*)?(?:[kKmMbB])?)/,
    unit_literal: _ => token(prec(2, /\d+(?:\.\d+)?\p{XID_Start}[\p{XID_Continue}-]*(?:\d+(?:\.\d+)?\p{XID_Start}[\p{XID_Continue}-]*)*/u)),
    decimal_quantity: _ => /\d+(?:\.\d+)?/,
    datetime: _ => token(prec(4, /\d{4}-\d{1,2}-\d{1,2}T\d{1,2}:\d{2}(?::\d{2}(?:\.\d+)?)?(?:Z|[+-]\d{2}:?\d{2})?/)),
    date: _ => token(prec(3, /\d{4}[-\/.]\d{1,2}[-\/.]\d{1,2}|\d{1,2}[-\/.]\d{1,2}[-\/.]\d{4}/)),
    time: _ => token(prec(3, /\d{1,3}:\d{1,2}(?::\d{1,2})?/)),
    string: _ => /'(?:''|\\.|[^'\\])*'|"(?:""|\\.|[^"\\])*"/,
    comment: _ => token(/#[^\r\n]*/),
  },
});
